"""Egress: the squid configuration for a session's allowlist proxy.

Every mode refuses private, loopback, link-local, reserved and the VM's own addresses (after DNS
resolution, so a public name pointing at the LAN is refused too). CONNECT goes only to 443 and plain
HTTP only to 80/443, except the local model server's port.
"""
import ipaddress
import re
import socket
import subprocess

from .errors import AgentboxError

MODES = ("locked", "packages", "open")
PROXY_PORT = 3128

PRIVATE = ["0.0.0.0/8", "10.0.0.0/8", "100.64.0.0/10", "127.0.0.0/8", "169.254.0.0/16", "172.16.0.0/12",
           "192.0.0.0/24", "192.168.0.0/16", "198.18.0.0/15", "224.0.0.0/4", "240.0.0.0/4",
           "::/128", "::1", "fc00::/7", "fe80::/10", "ff00::/8"]

PACKAGES = ["pypi.org", ".pythonhosted.org", "registry.npmjs.org", "crates.io", ".crates.io",
            "github.com", ".github.com", ".githubusercontent.com", ".debian.org", ".ubuntu.com",
            "dl-cdn.alpinelinux.org", "conda.anaconda.org", "repo.anaconda.com", "cloud.r-project.org",
            "bioconductor.org", ".bioconductor.org"]

DOMAIN = re.compile(r"^\.?([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")


def check_domains(domains, where):
    out = []
    for d in domains:
        d = d.strip().lower()
        if not DOMAIN.match(d):
            raise AgentboxError(f"{where}: {d!r} is not a domain name (use example.com or .example.com)")
        out.append(d)
    return out


def dedupe(domains):
    """Squid refuses `x.com` together with `.x.com` in one acl (the dot form already covers x.com)."""
    s = set(domains)
    return sorted(d for d in s if not (not d.startswith(".") and "." + d in s))


def host_addresses():
    """The VM's own addresses, refused in every mode even if they are not private."""
    out = set()
    try:
        p = subprocess.run(["ip", "-o", "addr", "show"], capture_output=True, text=True, timeout=10)
        for m in re.finditer(r"\binet6? ([0-9a-fA-F:.]+)/\d+", p.stdout):
            out.add(m.group(1))
    except (OSError, subprocess.TimeoutExpired):
        pass
    try:
        out.update(ai[4][0] for ai in socket.getaddrinfo(socket.gethostname(), None))
    except OSError:
        pass
    good = []
    for a in out:
        try:
            ip = ipaddress.ip_address(a.split("%")[0])
        except ValueError:
            continue
        good.append(str(ip))
    return sorted(good)


def squid_conf(mode, *, model_domains, model_host, model_port, extra_domains=(), host_addrs=(), dns=None):
    if mode not in MODES:
        raise AgentboxError(f"unknown egress mode {mode!r}")
    if not host_addrs:
        raise AgentboxError("squid_conf: no host addresses to refuse; refusing to build a config without them")
    host_addrs = [str(ipaddress.ip_address(a)) for a in host_addrs]
    model_domains = check_domains(model_domains, "model domains")
    extra = check_domains(extra_domains, "extra_domains")
    ipaddress.ip_address(model_host)
    lines = [
        "# generated by agentbox; one session, one mode: " + mode,
        f"http_port {PROXY_PORT}",
        "visible_hostname agentbox-proxy",
        "via off",
        "forwarded_for delete",
        "httpd_suppress_version_string on",
        "pinger_enable off",
    ]
    if dns:
        lines.append(f"dns_nameservers {dns}")
    lines += [
        f"acl localmodel dst {model_host}",
        f"acl modelport port {int(model_port)}",
        "acl private dst " + " ".join(PRIVATE),
    ]
    lines.append("acl hostaddr dst " + " ".join(host_addrs))
    lines += [
        "acl CONNECT method CONNECT",
        "acl sslport port 443",
        "acl webports port 80 443",
    ]
    allow = []
    if model_domains:       # none for an agent that only uses the local model server
        lines.append("acl models dstdomain " + " ".join(dedupe(model_domains)))
        allow.append("http_access allow models")
    if mode in ("packages", "open"):
        lines.append("acl packages dstdomain " + " ".join(dedupe(PACKAGES)))
        allow.append("http_access allow packages")
        if extra:
            lines.append("acl extra dstdomain " + " ".join(dedupe(extra)))
            allow.append("http_access allow extra")
    if mode == "open":
        allow.append("http_access allow all")
    lines += [
        "http_access allow localmodel modelport",
        "http_access deny private",
    ]
    lines.append("http_access deny hostaddr")
    lines += [
        "http_access deny CONNECT !sslport",
        "http_access deny !webports",
    ] + allow + [
        "http_access deny all",
        "cache deny all",
        "cache_mem 8 MB",
        # destinations only (host:port), never URL paths or queries, which can carry data
        "strip_query_terms on",
        "logformat agentbox %ts.%03tu %>a %rm %>rd:%>rP %>Hs %<a %Ss/%Sh",
        "access_log stdio:/dev/stdout agentbox",
        "cache_log stdio:/dev/stderr",
        "pid_filename none",
        "shutdown_lifetime 1 seconds",
    ]
    return "\n".join(lines) + "\n"


def proxy_env(proxy_host):
    url = f"http://{proxy_host}:{PROXY_PORT}"
    no_proxy = "localhost,127.0.0.1,::1"
    env = {}
    for k in ("HTTP_PROXY", "HTTPS_PROXY", "http_proxy", "https_proxy"):
        env[k] = url
    env["NO_PROXY"] = env["no_proxy"] = no_proxy
    return env
